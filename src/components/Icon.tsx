export type IconName = keyof typeof iconMap;

export function Icon({
    name,
    size = 16,
    strokeWidth = 1.8,
}: {
    name: IconName;
    size?: number;
    strokeWidth?: number;
}) {
    const IconComponent = iconMap[name];
    return (
        <IconComponent size={size} strokeWidth={strokeWidth} aria-hidden="true" />
    );
}
